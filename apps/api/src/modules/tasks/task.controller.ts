import { Response } from 'express';
import { DataStore } from '../store';
import { createTaskSchema, updateTaskStatusSchema } from '@grand-bandhan/validation';
import { AuthenticatedRequest } from '../../middleware/auth';
import { generateInstantWeddingPlan } from './task.service';
import { broadcastWeddingUpdate } from '../../socket';
import { SOCKET_EVENTS, TaskStatus } from '@grand-bandhan/shared';

export function listTasks(req: AuthenticatedRequest, res: Response): void {
  const weddingId = req.query.weddingId as string;
  if (!weddingId) {
    res.status(400).json({ success: false, message: 'weddingId query parameter is required' });
    return;
  }

  const tasks = DataStore.tasks.listByWedding(weddingId);
  res.json({ success: true, data: tasks });
}

export function createTask(req: AuthenticatedRequest, res: Response): void {
  const parsed = createTaskSchema.parse(req.body);
  const task = DataStore.tasks.create({
    weddingId: parsed.weddingId,
    title: parsed.title,
    description: parsed.description || null,
    category: parsed.category,
    deadline: new Date(parsed.deadline).toISOString(),
    priority: parsed.priority,
    status: parsed.status,
    assignedUserId: parsed.assignedUserId || null,
    vendorId: parsed.vendorId || null,
    eventId: parsed.eventId || null,
    isAutoGenerated: false,
  });

  broadcastWeddingUpdate(parsed.weddingId, SOCKET_EVENTS.TASK_STATUS_UPDATED, { task });
  res.status(201).json({ success: true, data: task });
}

export function updateTask(req: AuthenticatedRequest, res: Response): void {
  const id = String(req.params.id);
  const parsed = updateTaskStatusSchema.parse(req.body);

  const existing = DataStore.tasks.findById(id);
  if (!existing) {
    res.status(404).json({ success: false, message: 'Task not found' });
    return;
  }

  const updated = DataStore.tasks.update(id, {
    status: parsed.status,
    ...(parsed.assignedUserId !== undefined ? { assignedUserId: parsed.assignedUserId } : {}),
    ...(parsed.status === TaskStatus.DONE ? { completedAt: new Date().toISOString() } : {}),
  });

  broadcastWeddingUpdate(existing.weddingId, SOCKET_EVENTS.TASK_STATUS_UPDATED, { task: updated });
  res.json({ success: true, data: updated });
}

export function regeneratePlan(req: AuthenticatedRequest, res: Response): void {
  const { weddingId } = req.body;
  const wedding = DataStore.weddings.findById(weddingId);
  if (!wedding) {
    res.status(404).json({ success: false, message: 'Wedding not found' });
    return;
  }

  const tasks = generateInstantWeddingPlan(wedding.id, wedding.weddingDate, wedding.packageType);
  broadcastWeddingUpdate(weddingId, SOCKET_EVENTS.TASK_STATUS_UPDATED, { count: tasks.length });

  res.json({
    success: true,
    data: tasks,
    message: `Regenerated ${tasks.length} instant planning tasks calculated from wedding date with dynamic lead times.`,
  });
}
