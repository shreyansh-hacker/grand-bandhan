import { Response } from 'express';
import { prisma } from '@grand-bandhan/database';
import { createTaskSchema, updateTaskStatusSchema } from '@grand-bandhan/validation';
import { AuthenticatedRequest } from '../../middleware/auth';
import { generateInstantWeddingPlan } from './task.service';
import { broadcastWeddingUpdate } from '../../socket';
import { SOCKET_EVENTS, TaskStatus, UserRole } from '@grand-bandhan/shared';
import { NotificationService } from '../notifications/notification.service';
import { NotificationEvent } from '../notifications/notification.types';

export async function listTasks(req: AuthenticatedRequest, res: Response): Promise<void> {
  const weddingId = req.query.weddingId as string;
  if (!weddingId) {
    res.status(400).json({ success: false, message: 'weddingId query parameter is required' });
    return;
  }

  try {
    const wedding = await prisma.wedding.findUnique({
      where: { id: weddingId },
      select: { agencyId: true },
    });

    if (!wedding) {
      res.status(404).json({ success: false, message: 'Wedding project not found' });
      return;
    }

    if (req.user?.role !== UserRole.SUPER_ADMIN && wedding.agencyId !== req.user?.agencyId) {
      res.status(403).json({ success: false, message: 'Access denied to this wedding' });
      return;
    }

    const tasks = await prisma.task.findMany({
      where: { weddingId },
      include: {
        assignedUser: { select: { id: true, name: true, email: true, phone: true } },
        vendor: { select: { id: true, name: true, category: true } },
      },
      orderBy: { deadline: 'asc' },
    });

    res.json({ success: true, data: tasks });
  } catch (err: any) {
    res.status(500).json({ success: false, message: err.message });
  }
}

export async function createTask(req: AuthenticatedRequest, res: Response): Promise<void> {
  try {
    const parsed = createTaskSchema.parse(req.body);

    const wedding = await prisma.wedding.findUnique({
      where: { id: parsed.weddingId },
      select: { agencyId: true },
    });

    if (!wedding) {
      res.status(404).json({ success: false, message: 'Wedding not found' });
      return;
    }

    if (req.user?.role !== UserRole.SUPER_ADMIN && wedding.agencyId !== req.user?.agencyId) {
      res.status(403).json({ success: false, message: 'Access denied' });
      return;
    }

    const task = await prisma.task.create({
      data: {
        weddingId: parsed.weddingId,
        title: parsed.title,
        description: parsed.description || null,
        category: parsed.category,
        deadline: new Date(parsed.deadline),
        priority: parsed.priority,
        status: parsed.status,
        assignedUserId: parsed.assignedUserId || null,
        vendorId: parsed.vendorId || null,
        eventId: parsed.eventId || null,
        isAutoGenerated: false,
      },
    });

    broadcastWeddingUpdate(parsed.weddingId, SOCKET_EVENTS.TASK_STATUS_UPDATED, { task });

    // Emit Task Assigned event if assigned to staff
    if (parsed.assignedUserId) {
      try {
        const assignedUser = await prisma.user.findUnique({
          where: { id: parsed.assignedUserId },
          select: { name: true, email: true },
        });
        const weddingDetail = await prisma.wedding.findUnique({
          where: { id: parsed.weddingId },
          select: { weddingCode: true, agencyId: true },
        });
        if (assignedUser && assignedUser.email) {
          await NotificationService.emit(NotificationEvent.TASK_ASSIGNED, {
            agencyId: weddingDetail?.agencyId,
            recipientEmail: assignedUser.email,
            recipientName: assignedUser.name,
            recipientRole: 'STAFF',
            data: {
              taskTitle: task.title,
              category: task.category,
              priority: task.priority,
              dueDate: task.deadline?.toISOString(),
              weddingCode: weddingDetail?.weddingCode,
            },
          });
        }
      } catch (notifErr: any) {
        console.warn('[Task] Could not emit TASK_ASSIGNED notification:', notifErr.message);
      }
    }

    res.status(201).json({ success: true, data: task });
  } catch (err: any) {
    if (err.errors) {
      res.status(400).json({ success: false, errors: err.errors });
      return;
    }
    res.status(500).json({ success: false, message: err.message });
  }
}

export async function updateTask(req: AuthenticatedRequest, res: Response): Promise<void> {
  const id = String(req.params.id);
  try {
    const parsed = updateTaskStatusSchema.parse(req.body);

    const existing = await prisma.task.findUnique({
      where: { id },
      include: { wedding: { select: { agencyId: true } } },
    });

    if (!existing) {
      res.status(404).json({ success: false, message: 'Task not found' });
      return;
    }

    if (req.user?.role !== UserRole.SUPER_ADMIN && existing.wedding.agencyId !== req.user?.agencyId) {
      res.status(403).json({ success: false, message: 'Access denied' });
      return;
    }

    const updated = await prisma.task.update({
      where: { id },
      data: {
        status: parsed.status,
        ...(parsed.assignedUserId !== undefined ? { assignedUserId: parsed.assignedUserId } : {}),
        ...(parsed.status === TaskStatus.DONE ? { completedAt: new Date() } : {}),
      },
    });

    broadcastWeddingUpdate(existing.weddingId, SOCKET_EVENTS.TASK_STATUS_UPDATED, { task: updated });

    if (parsed.assignedUserId && parsed.assignedUserId !== existing.assignedUserId) {
      try {
        const assignedUser = await prisma.user.findUnique({
          where: { id: parsed.assignedUserId },
          select: { name: true, email: true },
        });
        const weddingDetail = await prisma.wedding.findUnique({
          where: { id: existing.weddingId },
          select: { weddingCode: true, agencyId: true },
        });
        if (assignedUser && assignedUser.email) {
          await NotificationService.emit(NotificationEvent.TASK_ASSIGNED, {
            agencyId: weddingDetail?.agencyId,
            recipientEmail: assignedUser.email,
            recipientName: assignedUser.name,
            recipientRole: 'STAFF',
            data: {
              taskTitle: updated.title,
              category: updated.category,
              priority: updated.priority,
              dueDate: updated.deadline?.toISOString(),
              weddingCode: weddingDetail?.weddingCode,
            },
          });
        }
      } catch (notifErr: any) {
        console.warn('[Task] Could not emit TASK_ASSIGNED notification:', notifErr.message);
      }
    }

    res.json({ success: true, data: updated });
  } catch (err: any) {
    if (err.errors) {
      res.status(400).json({ success: false, errors: err.errors });
      return;
    }
    res.status(500).json({ success: false, message: err.message });
  }
}

export async function regeneratePlan(req: AuthenticatedRequest, res: Response): Promise<void> {
  const { weddingId } = req.body;
  try {
    const wedding = await prisma.wedding.findUnique({
      where: { id: weddingId },
      select: { id: true, weddingDate: true, packageType: true, agencyId: true },
    });

    if (!wedding) {
      res.status(404).json({ success: false, message: 'Wedding not found' });
      return;
    }

    if (req.user?.role !== UserRole.SUPER_ADMIN && wedding.agencyId !== req.user?.agencyId) {
      res.status(403).json({ success: false, message: 'Access denied' });
      return;
    }

    const tasks = await generateInstantWeddingPlan(wedding.id, wedding.weddingDate, wedding.packageType as any);
    broadcastWeddingUpdate(weddingId, SOCKET_EVENTS.TASK_STATUS_UPDATED, { count: tasks.length });

    res.json({
      success: true,
      data: tasks,
      message: `Regenerated ${tasks.length} instant planning tasks calculated from wedding date with dynamic lead times.`,
    });
  } catch (err: any) {
    res.status(500).json({ success: false, message: err.message });
  }
}
